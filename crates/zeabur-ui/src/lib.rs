pub use embedded::KIND;

/// Content Security Policy for the interface's HTML.
///
/// Scripts, fonts and API calls come from this origin only, nothing may frame the page, and
/// scripts may not write HTML strings into the DOM (Trusted Types with no policy). The build emits
/// no inline script, so `script-src 'self'` needs neither a hash nor `'unsafe-inline'`;
/// `scripts/build-ui.sh` fails if `index.html` gains an inline script or style.
///
/// Styles also allow `'unsafe-inline'`: two libraries add `<style>` elements at run time. Sonner
/// (toasts) inserts a fixed style sheet when its module loads and has no nonce option
/// ([sonner#449]); CodeMirror (the YAML editor) inserts its theme's rules. Without the keyword,
/// both are refused (`style-src` governs `<style>` elements, [mdn-style-src]). Inline styles can
/// restyle the page but not run code; script execution stays restricted to this origin.
///
/// [sonner#449]: https://github.com/emilkowalski/sonner/issues/449
/// [mdn-style-src]: https://developer.mozilla.org/en-US/docs/Web/HTTP/Reference/Headers/Content-Security-Policy/style-src
pub const CSP: &str = "default-src 'none'; script-src 'self'; style-src 'self' 'unsafe-inline'; \
img-src 'self' data:; font-src 'self'; connect-src 'self'; manifest-src 'self'; base-uri 'none'; \
form-action 'self'; frame-ancestors 'none'; require-trusted-types-for 'script'; \
trusted-types 'none'";

/// `Cache-Control` for files whose name carries their content hash.
const IMMUTABLE: &str = "public, max-age=31536000, immutable";
/// `Cache-Control` for everything else, `index.html` in particular: the browser may keep a copy
/// but must revalidate it (with `If-None-Match`) before every use.
const REVALIDATE: &str = "no-cache";

/// What this binary embeds.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum EmbeddedKind {
    /// The built interface from `ZEABUR_UI_DIST`.
    Dist,
    /// The one-page placeholder of a debug build without `ZEABUR_UI_DIST`.
    Placeholder,
}

/// One embedded file and its precompressed encodings.
#[derive(Debug)]
pub struct Asset {
    /// Path relative to the site root, without a leading `/`.
    pub path: &'static str,
    /// Value of `Content-Type`.
    pub content_type: &'static str,
    /// Strong entity tag of the unencoded file, quotes included.
    pub etag: &'static str,
    /// Whether the file name carries a content hash, so the response can be cached forever.
    pub immutable: bool,
    /// The file itself.
    pub identity: &'static [u8],
    /// Its brotli encoding, when smaller.
    pub brotli: Option<&'static [u8]>,
}

/// The embedded files.
#[must_use]
pub fn assets() -> &'static [Asset] {
    embedded::ASSETS
}

/// A router that serves the embedded interface for every path it receives.
///
/// Mount it as the fallback of the application router, after the API routes.
pub fn router() -> Router {
    router_for(assets())
}

/// A router that serves `assets`; [`router`] with the embedded files.
pub fn router_for(assets: &'static [Asset]) -> Router {
    Router::new().fallback(move |request: Request<Body>| async move {
        respond(
            assets,
            request.method(),
            request.uri().path(),
            request.headers(),
        )
    })
}

/// Whether `path` is a page of the interface: a client-side route answered with `index.html`,
/// not a file, an API path or a missing build output.
#[must_use]
pub fn is_page(path: &str) -> bool {
    is_page_in(assets(), path)
}

/// [`is_page`] for `assets`.
#[must_use]
pub fn is_page_in(assets: &[Asset], path: &str) -> bool {
    let path = path.trim_start_matches('/');
    if path == "api" || path.starts_with("api/") || path.starts_with("assets/") {
        return false;
    }
    path.is_empty() || path == "index.html" || !assets.iter().any(|a| a.path == path)
}

/// Answers one request for a file of the interface.
///
/// - Paths under `/api` are never the interface: an unknown API path is a `404`, not a page.
/// - A known file is served as is. An unknown path is a client-side route, answered with
///   `index.html` (the single-page fallback), except under `assets/`: those names are generated by
///   the build, and an HTML page in place of a missing script would only hide the error.
/// - Brotli when `Accept-Encoding` allows it and the file has an encoding; otherwise the file
///   itself.
#[must_use]
pub fn respond(assets: &[Asset], method: &Method, path: &str, headers: &HeaderMap) -> Response {
    if method != Method::GET && method != Method::HEAD {
        return status(StatusCode::METHOD_NOT_ALLOWED, |h| {
            h.insert(header::ALLOW, HeaderValue::from_static("GET, HEAD"));
        });
    }
    let path = path.trim_start_matches('/');
    if path == "api" || path.starts_with("api/") {
        return not_found();
    }
    let wanted = if path.is_empty() { "index.html" } else { path };
    let asset = match assets.iter().find(|a| a.path == wanted) {
        Some(asset) => asset,
        None if wanted.starts_with("assets/") => return not_found(),
        None => match assets.iter().find(|a| a.path == "index.html") {
            Some(index) => index,
            None => return not_found(),
        },
    };
    let (body, encoding) = negotiate(asset, headers);
    let etag = etag(asset, encoding);
    let not_modified = if_none_match(headers, &etag);

    let mut response = if not_modified || method == Method::HEAD {
        Response::new(Body::empty())
    } else {
        Response::new(Body::from(body))
    };
    if not_modified {
        *response.status_mut() = StatusCode::NOT_MODIFIED;
    }
    let h = response.headers_mut();
    insert(h, header::CONTENT_TYPE, asset.content_type);
    insert(
        h,
        header::CACHE_CONTROL,
        if asset.immutable {
            IMMUTABLE
        } else {
            REVALIDATE
        },
    );
    if let Ok(value) = HeaderValue::from_str(&etag) {
        h.insert(header::ETAG, value);
    }
    if asset.brotli.is_some() {
        insert(h, header::VARY, "accept-encoding");
    }
    if let Some(coding) = encoding.token() {
        insert(h, header::CONTENT_ENCODING, coding);
    }
    if method == Method::HEAD && !not_modified {
        h.insert(header::CONTENT_LENGTH, HeaderValue::from(body.len()));
    }
    harden(h, asset.content_type.starts_with("text/html"));
    response
}

/// A content coding the server can send.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Coding {
    Identity,
    Brotli,
}

impl Coding {
    const fn token(self) -> Option<&'static str> {
        match self {
            Self::Identity => None,
            Self::Brotli => Some("br"),
        }
    }
}

fn negotiate(asset: &Asset, headers: &HeaderMap) -> (&'static [u8], Coding) {
    let accept = headers
        .get_all(header::ACCEPT_ENCODING)
        .iter()
        .filter_map(|v| v.to_str().ok())
        .collect::<Vec<_>>()
        .join(",");
    if let Some(body) = asset.brotli.filter(|_| accepts(&accept, "br")) {
        return (body, Coding::Brotli);
    }
    (asset.identity, Coding::Identity)
}

/// Whether `Accept-Encoding` allows `coding`: listed (or matched by `*`) with a non-zero weight.
fn accepts(accept: &str, coding: &str) -> bool {
    let mut wildcard = None;
    for item in accept.split(',') {
        let mut parts = item.split(';').map(str::trim);
        let name = parts.next().unwrap_or_default();
        let allowed = parts
            .filter_map(|p| p.strip_prefix("q=").or_else(|| p.strip_prefix("Q=")))
            .all(|q| q.parse::<f32>().is_ok_and(|q| q > 0.0));
        if name.eq_ignore_ascii_case(coding) {
            return allowed;
        }
        if name == "*" {
            wildcard = Some(allowed);
        }
    }
    wildcard.unwrap_or(false)
}

/// Each encoding is a different representation, so it gets its own strong entity tag.
fn etag(asset: &Asset, coding: Coding) -> String {
    let base = asset.etag.trim_matches('"');
    coding.token().map_or_else(
        || format!("\"{base}\""),
        |token| format!("\"{base}-{token}\""),
    )
}

/// `If-None-Match` with the weak comparison it requires: a match on any listed tag, ignoring a
/// `W/` prefix, or `*`.
fn if_none_match(headers: &HeaderMap, etag: &str) -> bool {
    headers
        .get_all(header::IF_NONE_MATCH)
        .iter()
        .filter_map(|v| v.to_str().ok())
        .flat_map(|v| v.split(','))
        .map(str::trim)
        .any(|tag| tag == "*" || tag.trim_start_matches("W/") == etag)
}

fn harden(headers: &mut HeaderMap, html: bool) {
    insert(headers, header::X_CONTENT_TYPE_OPTIONS, "nosniff");
    insert(
        headers,
        header::HeaderName::from_static("cross-origin-resource-policy"),
        "same-origin",
    );
    if html {
        insert(headers, header::CONTENT_SECURITY_POLICY, CSP);
        insert(headers, header::X_FRAME_OPTIONS, "DENY");
        insert(headers, header::REFERRER_POLICY, "no-referrer");
        insert(
            headers,
            header::HeaderName::from_static("cross-origin-opener-policy"),
            "same-origin",
        );
        insert(
            headers,
            header::HeaderName::from_static("permissions-policy"),
            "camera=(), microphone=(), geolocation=()",
        );
    }
}

fn insert(headers: &mut HeaderMap, name: header::HeaderName, value: &'static str) {
    headers.insert(name, HeaderValue::from_static(value));
}

fn not_found() -> Response {
    let mut response = status(StatusCode::NOT_FOUND, |_| {});
    *response.body_mut() = Body::from(r#"{"type":"about:blank","title":"Not Found","status":404}"#);
    insert(
        response.headers_mut(),
        header::CONTENT_TYPE,
        "application/problem+json",
    );
    response
}

fn status(code: StatusCode, headers: impl FnOnce(&mut HeaderMap)) -> Response {
    let mut response = Response::new(Body::empty());
    *response.status_mut() = code;
    headers(response.headers_mut());
    insert(
        response.headers_mut(),
        header::X_CONTENT_TYPE_OPTIONS,
        "nosniff",
    );
    response
}

#[cfg(test)]
mod tests {
    use axum::body::to_bytes;

    use super::*;

    static TEST_ASSETS: &[Asset] = &[
        Asset {
            path: "index.html",
            content_type: "text/html; charset=utf-8",
            etag: "\"aaaa\"",
            immutable: false,
            identity: b"<html>index</html>",
            brotli: Some(b"BR-INDEX"),
        },
        Asset {
            path: "assets/index-3f2a.js",
            content_type: "text/javascript; charset=utf-8",
            etag: "\"bbbb\"",
            immutable: true,
            identity: b"console.log(1)",
            brotli: None,
        },
    ];

    fn get(path: &str, headers: &[(&'static str, &'static str)]) -> Response {
        let mut map = HeaderMap::new();
        for (name, value) in headers {
            map.append(*name, HeaderValue::from_static(value));
        }
        respond(TEST_ASSETS, &Method::GET, path, &map)
    }

    async fn body(response: Response) -> Vec<u8> {
        to_bytes(response.into_body(), 1 << 20)
            .await
            .unwrap()
            .to_vec()
    }

    fn header<'a>(response: &'a Response, name: &str) -> Option<&'a str> {
        response.headers().get(name).and_then(|v| v.to_str().ok())
    }

    #[tokio::test]
    async fn index_is_revalidated_and_hardened() {
        let response = get("/", &[]);
        assert_eq!(response.status(), StatusCode::OK);
        assert_eq!(header(&response, "cache-control"), Some("no-cache"));
        assert_eq!(header(&response, "etag"), Some("\"aaaa\""));
        assert_eq!(header(&response, "content-security-policy"), Some(CSP));
        let csp = header(&response, "content-security-policy").unwrap_or_default();
        assert!(csp.contains("; script-src 'self';"), "{csp}");
        assert!(csp.contains("; style-src 'self' 'unsafe-inline';"), "{csp}");
        assert_eq!(header(&response, "vary"), Some("accept-encoding"));
        assert_eq!(body(response).await, b"<html>index</html>");
    }

    #[test]
    fn hashed_files_are_immutable_and_not_hardened_as_html() {
        let response = get("/assets/index-3f2a.js", &[]);
        assert_eq!(
            header(&response, "cache-control"),
            Some("public, max-age=31536000, immutable")
        );
        assert_eq!(header(&response, "content-security-policy"), None);
        assert_eq!(header(&response, "x-content-type-options"), Some("nosniff"));
    }

    #[tokio::test]
    async fn client_routes_fall_back_to_index() {
        let response = get("/projects/demo/services/web", &[]);
        assert_eq!(response.status(), StatusCode::OK);
        assert_eq!(body(response).await, b"<html>index</html>");
    }

    /// Every problem's `type` leads to a page of the interface, which explains it.
    #[tokio::test]
    async fn every_problem_type_is_a_page() {
        for kind in zeabur_core::problem::Kind::ALL {
            let response = get(kind.type_uri(), &[]);
            assert_eq!(response.status(), StatusCode::OK, "{kind:?}");
            assert_eq!(body(response).await, b"<html>index</html>", "{kind:?}");
        }
    }

    #[test]
    fn missing_build_outputs_and_api_paths_are_not_found() {
        for path in ["/assets/gone-1234.js", "/api", "/api/v1/nothing"] {
            let response = get(path, &[]);
            assert_eq!(response.status(), StatusCode::NOT_FOUND, "{path}");
            assert_eq!(
                header(&response, "content-type"),
                Some("application/problem+json")
            );
        }
    }

    #[test]
    fn pages_are_routes_not_files() {
        for path in ["/", "/index.html", "/projects/demo", "//elsewhere.example/"] {
            assert!(is_page_in(TEST_ASSETS, path), "{path}");
        }
        for path in [
            "/assets/index-3f2a.js",
            "/assets/gone-1234.js",
            "/api",
            "/api/v1/x",
        ] {
            assert!(!is_page_in(TEST_ASSETS, path), "{path}");
        }
    }

    #[tokio::test]
    async fn brotli_when_accepted_else_the_file_itself() {
        let response = get("/", &[("accept-encoding", "gzip, deflate, br")]);
        assert_eq!(header(&response, "content-encoding"), Some("br"));
        assert_eq!(header(&response, "etag"), Some("\"aaaa-br\""));
        assert_eq!(body(response).await, b"BR-INDEX");

        let response = get("/", &[("accept-encoding", "br;q=0, gzip")]);
        assert_eq!(header(&response, "content-encoding"), None);
        assert_eq!(header(&response, "etag"), Some("\"aaaa\""));
        assert_eq!(body(response).await, b"<html>index</html>");

        let response = get("/assets/index-3f2a.js", &[("accept-encoding", "br")]);
        assert_eq!(header(&response, "content-encoding"), None);

        let response = get("/", &[("accept-encoding", "*;q=0")]);
        assert_eq!(header(&response, "content-encoding"), None);
    }

    #[tokio::test]
    async fn matching_if_none_match_is_not_modified() {
        let response = get(
            "/",
            &[
                ("accept-encoding", "br"),
                ("if-none-match", "\"x\", W/\"aaaa-br\""),
            ],
        );
        assert_eq!(response.status(), StatusCode::NOT_MODIFIED);
        assert_eq!(header(&response, "etag"), Some("\"aaaa-br\""));
        assert_eq!(body(response).await, b"");

        // The tag of another encoding is another representation.
        let response = get("/", &[("if-none-match", "\"aaaa-br\"")]);
        assert_eq!(response.status(), StatusCode::OK);
    }

    #[tokio::test]
    async fn head_has_headers_without_a_body() {
        let response = respond(TEST_ASSETS, &Method::HEAD, "/", &HeaderMap::new());
        assert_eq!(header(&response, "content-length"), Some("18"));
        assert_eq!(body(response).await, b"");
    }

    #[test]
    fn other_methods_are_refused() {
        let response = respond(TEST_ASSETS, &Method::POST, "/", &HeaderMap::new());
        assert_eq!(response.status(), StatusCode::METHOD_NOT_ALLOWED);
        assert_eq!(header(&response, "allow"), Some("GET, HEAD"));
    }

    /// CI builds with `ZEABUR_UI_DIST` set: the binary must then carry the built interface, with
    /// its encodings, and not the placeholder.
    #[test]
    fn a_build_with_a_dist_embeds_it() {
        if option_env!("ZEABUR_UI_DIST").is_some_and(|d| !d.is_empty()) {
            assert_eq!(KIND, EmbeddedKind::Dist);
            assert!(assets().iter().any(|a| a.immutable && a.brotli.is_some()));
        } else {
            assert_eq!(KIND, EmbeddedKind::Placeholder);
        }
    }
}
