// Writes src/api/rules.ts: the limits, patterns and defaults the server's OpenAPI description sets
// on the fields it is sent, so a form checks what the server checks. orval keeps them only as
// comments.
// Usage: bun scripts/gen-rules.ts <openapi.yaml> <rules.ts>
import { readFileSync, writeFileSync } from "node:fs"

interface Schema {
  properties?: Record<string, Schema>
  oneOf?: Schema[]
  enum?: unknown[]
  maxLength?: number
  minLength?: number
  pattern?: string
  minimum?: number
  maximum?: number
  default?: unknown
}

const [input, output] = process.argv.slice(2)
if (!input || !output) throw new Error("usage: bun scripts/gen-rules.ts <openapi.yaml> <rules.ts>")
const spec = Bun.YAML.parse(readFileSync(input, "utf8")) as {
  components: { schemas: Record<string, Schema> }
}

/** Every unsigned integer has `minimum: 0`; only a higher one is a rule. */
function rule({ maxLength, minLength, pattern, minimum, maximum, default: fallback }: Schema) {
  const found = {
    maxLength,
    minLength,
    pattern,
    minimum: minimum === 0 ? undefined : minimum,
    maximum,
    default: fallback,
  }
  const kept = Object.entries(found).filter(([, value]) => value !== undefined)
  return kept.length > 0 ? Object.fromEntries(kept) : undefined
}

/** A variant of a tagged union is named by the one value of its tag. */
function tag(variant: Schema): string | undefined {
  const tags = Object.values(variant.properties ?? {}).filter((p) => p.enum?.length === 1)
  return tags.length === 1 ? String(tags[0]?.enum?.[0]) : undefined
}

const rules: Record<string, object> = {}
function collect(prefix: string, schema: Schema) {
  for (const [name, property] of Object.entries(schema.properties ?? {})) {
    const found = rule(property)
    if (found) rules[`${prefix}.${name}`] = found
  }
}
for (const [name, schema] of Object.entries(spec.components.schemas)) {
  const own = rule(schema)
  if (own) rules[name] = own
  collect(name, schema)
  for (const variant of schema.oneOf ?? []) {
    const value = tag(variant)
    if (value) collect(`${name}.${value}`, variant)
  }
}

const sorted = Object.fromEntries(Object.entries(rules).sort(([a], [b]) => a.localeCompare(b)))
writeFileSync(
  output,
  `// Generated by scripts/gen-rules.ts from the OpenAPI description; do not edit.
// The limits, patterns and defaults the server checks, by schema, variant and field.
export const rules = ${JSON.stringify(sorted, null, 2)} as const
`,
)
